    private static string GenerateMappedCollectionAssignment(
        string destPropName, string sourceExpr, string destElemType,
        string mapperMethodName, CollectionKind kind)
    {
        // v10.0.0: Use lambda with null-forgiving operator to ensure non-nullable element type
        // This avoids CS8619 warnings about List<T?> vs List<T> nullability mismatches
        var selectExpr = $"{sourceExpr}?.Select(x => {mapperMethodName}(x)!)";

        return kind switch
        {
            CollectionKind.Array =>
                $"{destPropName} = {selectExpr}?.ToArray() ?? Array.Empty<{destElemType}>()",

            CollectionKind.HashSet =>
                $"{destPropName} = {selectExpr} != null ? new HashSet<{destElemType}>({selectExpr}) : new HashSet<{destElemType}>()",

            CollectionKind.SortedSet =>
                $"{destPropName} = {selectExpr} != null ? new SortedSet<{destElemType}>({selectExpr}) : new SortedSet<{destElemType}>()",

