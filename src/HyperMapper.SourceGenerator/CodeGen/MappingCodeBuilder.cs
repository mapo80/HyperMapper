/// <summary>
/// Generates C# mapping code from MappingDefinitions.
/// </summary>
internal class MappingCodeBuilder
{
    private const string GeneratorName = "HyperMapper.SourceGenerator";
    private const string GeneratorVersion = "7.1.0";

    public string GenerateMapperClass(ProfileInfo profile, Compilation compilation, SourceProductionContext context)
    {
        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// This code was generated by HyperMapper.SourceGenerator v7.1.0");
        sb.AppendLine("// Do not modify this file manually.");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Collections.ObjectModel;");  // v7.1.0: ObservableCollection support
        sb.AppendLine("using System.Linq;");
        sb.AppendLine();

        if (!string.IsNullOrEmpty(profile.Namespace))
        {
            sb.AppendLine($"namespace {profile.Namespace};");
            sb.AppendLine();
        }

        // Use FullClassName for nested types to ensure unique class names
        var generatedClassName = string.IsNullOrEmpty(profile.FullClassName)
            ? profile.ClassName
            : profile.FullClassName;

        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Generated mapper methods for {profile.ClassName}");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"{GeneratorName}\", \"{GeneratorVersion}\")]");
        sb.AppendLine($"internal static class {generatedClassName}GeneratedMappers");
        sb.AppendLine("{");

        foreach (var mapping in profile.Mappings)
        {
            // v7.1.0: Open generic mappings generate generic methods
            if (mapping.IsOpenGeneric)
            {
                GenerateOpenGenericMappingMethod(sb, mapping);
                sb.AppendLine();

                // Generate collection mapping method for open generics
                GenerateOpenGenericCollectionMappingMethod(sb, mapping);
                sb.AppendLine();
                continue;
            }

            // v7.1.0: Lambda converters can be inlined at compile-time
            if (mapping.HasConverter)
            {
                if (!string.IsNullOrEmpty(mapping.ConverterLambdaExpression))
                {
                    // Generate inline converter method
                    GenerateLambdaConverterMethod(sb, mapping);
                    sb.AppendLine();

                    // Generate collection mapping method for lambda converters
                    GenerateCollectionMappingMethod(sb, mapping);
                    sb.AppendLine();
                }
                // Skip class-based converters - they need runtime
                continue;
            }

            // v7.1.0: Value types (structs) are now fully supported at compile-time
            GenerateMappingMethod(sb, mapping, compilation, context);
            sb.AppendLine();

            // Generate collection mapping method
            GenerateCollectionMappingMethod(sb, mapping);
            sb.AppendLine();
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    private void GenerateMappingMethod(
        StringBuilder sb,
        MappingDefinition mapping,
        Compilation compilation,
        SourceProductionContext context)
    {
        var sourceType = mapping.SourceType;
        var destType = mapping.DestinationType;
        var methodName = GetMapperMethodName(mapping.SourceTypeName, mapping.DestinationTypeName);

        // v7.1.0: Support value types (structs)
        var isSourceValueType = mapping.SourceTypeSymbol?.IsValueType == true;
        var isDestValueType = mapping.DestinationTypeSymbol?.IsValueType == true;
        var isSourceNullableValueType = IsNullableValueType(mapping.SourceTypeSymbol);

        // v9.0.0: Check if we have custom constructor or ctor param mappings
        var hasCtorParams = mapping.CtorParamMappings.Count > 0;
        var hasCustomCtor = mapping.HasCustomConstructor && !string.IsNullOrEmpty(mapping.ConstructorLambdaExpression);

        // v7.1.0: Check if we have any PreConditions with extractable expressions
        var hasGeneratablePreConditions = mapping.MemberMappings
            .Any(m => m.HasPreCondition && !string.IsNullOrEmpty(m.PreConditionExpression));

        // v8.1.0: Check if we have any Conditions (post-mapping conditional)
        var hasGeneratableConditions = mapping.MemberMappings
            .Any(m => m.HasCondition && !string.IsNullOrEmpty(m.ConditionExpression));

        // v9.0.0: Check if we have ForPath mappings
        var hasPathMappings = mapping.PathMappings.Count > 0;

        // v10.0.0: Check if any MapFrom has destination parameter
        var hasDestinationParameterMappings = mapping.MemberMappings
            .Any(m => m.HasDestinationParameter);

        // v8.1.0: Need result variable if we have PreConditions OR Conditions
        // v9.0.0: Also need result variable if we have ctor params (to set remaining properties) or path mappings
        // v10.0.0: Also need result variable if we have MapFrom with destination parameter
        var needsResultVariable = hasGeneratablePreConditions || hasGeneratableConditions || hasCtorParams || hasPathMappings || hasDestinationParameterMappings;

        sb.AppendLine($"    /// <summary>");
        sb.AppendLine($"    /// Maps {sourceType} to {destType}");
        sb.AppendLine($"    /// </summary>");

        // Determine the source variable name to use in property access
        // For nullable value types, we extract .Value first, so use "sourceValue"
        var sourceVarName = isSourceNullableValueType ? "sourceValue" : "source";

        if (isSourceValueType && !isSourceNullableValueType)
        {
            // Non-nullable value type source - no null check needed
            // Return type depends on destination
            var returnType = isDestValueType ? destType : $"{destType}?";
            sb.AppendLine($"    public static {returnType} {methodName}({sourceType} source)");
            sb.AppendLine("    {");

            // v9.0.0: Handle ConstructUsing
            if (hasCustomCtor)
            {
                sb.AppendLine($"        return {mapping.ConstructorLambdaExpression};");
                sb.AppendLine("    }");
                return;
            }

            // v9.0.0: Handle ForCtorParam
            if (hasCtorParams)
            {
                GenerateCtorParamConstruction(sb, mapping, destType, sourceVarName);
            }
            else
            {
                // Use "result" variable if we have PreConditions or Conditions to allow post-initialization assignments
                if (needsResultVariable)
                    sb.AppendLine($"        var result = new {destType}");
                else
                    sb.AppendLine($"        return new {destType}");
                sb.AppendLine("        {");
            }
        }
        else
        {
            // Reference type or nullable value type - standard null handling
            sb.AppendLine($"    [return: global::System.Diagnostics.CodeAnalysis.NotNullIfNotNull(nameof(source))]");
            sb.AppendLine($"    public static {destType}? {methodName}({sourceType}? source)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (source is null) return null;");
            sb.AppendLine();

            // For nullable value types, we need to access .Value
            if (isSourceNullableValueType)
            {
                sb.AppendLine($"        var sourceValue = source.Value;");
            }

            // v9.0.0: Handle ConstructUsing
            if (hasCustomCtor)
            {
                var adjustedExpr = isSourceNullableValueType
                    ? mapping.ConstructorLambdaExpression!.Replace("source.", $"{sourceVarName}.")
                    : mapping.ConstructorLambdaExpression;
                sb.AppendLine($"        return {adjustedExpr};");
                sb.AppendLine("    }");
                return;
            }

            // v9.0.0: Handle ForCtorParam
            if (hasCtorParams)
            {
                GenerateCtorParamConstruction(sb, mapping, destType, sourceVarName);
            }
            else
            {
                // Use "result" variable if we have PreConditions or Conditions to allow post-initialization assignments
                if (needsResultVariable)
                    sb.AppendLine($"        var result = new {destType}");
                else
                    sb.AppendLine($"        return new {destType}");
                sb.AppendLine("        {");
            }
        }

        // If we used ConstructUsing, we already returned
        if (hasCustomCtor)
            return;

        // Get properties from type symbols
        var destProperties = GetWritableProperties(mapping.DestinationTypeSymbol);
        var sourceProperties = GetReadablePropertiesDict(mapping.SourceTypeSymbol);

        // v9.0.0: Build set of properties already mapped via ForCtorParam
        var ctorMappedParams = new HashSet<string>(
            mapping.CtorParamMappings.Select(c => c.ParameterName),
            StringComparer.OrdinalIgnoreCase);

        // Build lookup for custom mappings
        var ignoredMembers = new HashSet<string>(
            mapping.MemberMappings.Where(m => m.IsIgnored).Select(m => m.DestinationMember),
            StringComparer.Ordinal);

        var customMappings = mapping.MemberMappings
            .Where(m => !m.IsIgnored && m.SourceExpression != null)
            .ToDictionary(m => m.DestinationMember, m => m.SourceExpression!, StringComparer.Ordinal);

        // v7.1.0: Build PreCondition lookup with expressions
        var preConditionMappings = mapping.MemberMappings
            .Where(m => m.HasPreCondition && !string.IsNullOrEmpty(m.PreConditionExpression))
            .ToDictionary(m => m.DestinationMember, m => m, StringComparer.Ordinal);

        // v8.1.0: Build NullSubstitute lookup
        var nullSubstituteMappings = mapping.MemberMappings
            .Where(m => m.HasNullSubstitute && !string.IsNullOrEmpty(m.NullSubstituteExpression))
            .ToDictionary(m => m.DestinationMember, m => m.NullSubstituteExpression!, StringComparer.Ordinal);

        // v8.1.0: Build Condition lookup (post-mapping conditional)
        var conditionMappings = mapping.MemberMappings
            .Where(m => m.HasCondition && !string.IsNullOrEmpty(m.ConditionExpression))
            .ToDictionary(m => m.DestinationMember, m => m, StringComparer.Ordinal);

        // v10.0.0: Build transform lookup by type
        var transformsByType = mapping.Transforms
            .GroupBy(t => NormalizeTypeName(t.TargetType))
            .ToDictionary(g => g.Key, g => g.First().TransformExpression, StringComparer.Ordinal);

        // v10.0.0: Build lookup for MapFrom with destination parameter (needs result variable)
        var destParamMappings = mapping.MemberMappings
            .Where(m => m.HasDestinationParameter && !string.IsNullOrEmpty(m.SourceExpression))
            .ToDictionary(m => m.DestinationMember, m => m, StringComparer.Ordinal);

        // Generate property assignments for non-PreCondition and non-Condition properties
        foreach (var destProp in destProperties)
        {
            // Skip if ignored
            if (ignoredMembers.Contains(destProp.Name))
                continue;

            // Skip if has precondition (handled separately)
            if (preConditionMappings.ContainsKey(destProp.Name))
                continue;

            // Skip if has condition (handled separately after object initialization)
            if (conditionMappings.ContainsKey(destProp.Name))
                continue;

            // v10.0.0: Skip if has destination parameter (handled separately after object initialization)
            if (destParamMappings.ContainsKey(destProp.Name))
                continue;

            // v9.0.0: Skip if already mapped via ForCtorParam
            if (ctorMappedParams.Contains(destProp.Name))
                continue;

            string? assignment = null;

            if (customMappings.TryGetValue(destProp.Name, out var sourceExpr))
            {
                // Custom MapFrom expression - replace "source." with the correct var name
                var adjustedExpr = isSourceNullableValueType
                    ? sourceExpr.Replace("source.", $"{sourceVarName}.")
                    : sourceExpr;
                assignment = GenerateCustomMappingAssignment(destProp, adjustedExpr);
            }
            else if (sourceProperties.TryGetValue(destProp.Name, out var sourceProp))
            {
                // Convention-based mapping - same name
                assignment = GeneratePropertyAssignment(destProp, sourceProp, mapping, sourceVarName);
            }
            else
            {
                // Try flattening (e.g., AddressStreet -> Address.Street)
                assignment = TryGenerateFlatteningAssignment(destProp, sourceProperties, mapping.SourceTypeSymbol, sourceVarName);

                // v10.0.0: Try IncludeMembers - look for property in included member objects
                if (assignment == null && mapping.IncludedMembers.Count > 0)
                {
                    assignment = TryGenerateIncludeMembersAssignment(destProp, sourceProperties, mapping.IncludedMembers, sourceVarName);
                }
            }

            if (assignment != null)
            {
                // Extract the value expression from the assignment (e.g., "Name = source.Name" -> "source.Name")
                var equalIdx = assignment.IndexOf('=');
                var valueExpr = assignment.Substring(equalIdx + 1).Trim();

                // v10.0.0: Apply AddTransform if configured for this type
                if (transformsByType.Count > 0 && sourceProperties.TryGetValue(destProp.Name, out var srcPropForTransform))
                {
                    valueExpr = ApplyTransform(valueExpr, srcPropForTransform.Type, transformsByType);
                }

                // v8.1.0: Apply NullSubstitute if configured
                if (nullSubstituteMappings.TryGetValue(destProp.Name, out var nullSubstExpr))
                {
                    valueExpr = $"{valueExpr} ?? {nullSubstExpr}";
                }

                assignment = $"{destProp.Name} = {valueExpr}";

                // v9.0.0: If using ForCtorParam, assign directly to result instead of object initializer
                if (hasCtorParams)
                {
                    sb.AppendLine($"        result.{assignment};");
                }
                else
                {
                    sb.AppendLine($"            {assignment},");
                }
            }
        }

        // v9.0.0: Close object initializer only if not using ForCtorParam
        if (!hasCtorParams)
        {
            sb.AppendLine("        };");
        }

        // v7.1.0: Generate conditional assignments for PreCondition properties
        foreach (var kvp in preConditionMappings)
        {
            var destPropName = kvp.Key;
            var memberMapping = kvp.Value;

            // Find the destination property
            var destProp = destProperties.FirstOrDefault(p => p.Name == destPropName);
            if (destProp == null) continue;

            // Adjust PreCondition expression for nullable value types
            var preCondExpr = isSourceNullableValueType
                ? memberMapping.PreConditionExpression!.Replace("source.", $"{sourceVarName}.")
                : memberMapping.PreConditionExpression!;

            // Generate the value expression
            string? valueExpr = null;
            if (memberMapping.SourceExpression != null)
            {
                // Custom MapFrom expression
                var adjustedExpr = isSourceNullableValueType
                    ? memberMapping.SourceExpression.Replace("source.", $"{sourceVarName}.")
                    : memberMapping.SourceExpression;
                valueExpr = adjustedExpr;
            }
            else if (sourceProperties.TryGetValue(destPropName, out var sourceProp))
            {
                // Convention-based mapping
                valueExpr = $"{sourceVarName}.{sourceProp.Name}";
            }

            if (valueExpr != null)
            {
                // v10.0.0: Apply AddTransform if configured for this type
                if (transformsByType.Count > 0 && sourceProperties.TryGetValue(destPropName, out var srcPropForTransform))
                {
                    valueExpr = ApplyTransform(valueExpr, srcPropForTransform.Type, transformsByType);
                }

                // v8.1.0: Apply NullSubstitute if configured
                if (nullSubstituteMappings.TryGetValue(destPropName, out var nullSubstExpr))
                {
                    valueExpr = $"({valueExpr}) ?? {nullSubstExpr}";
                }

                sb.AppendLine();
                sb.AppendLine($"        if ({preCondExpr})");
                sb.AppendLine($"            result.{destPropName} = {valueExpr};");
            }
        }

        // v8.1.0: Generate conditional assignments for Condition properties (post-mapping conditional)
        foreach (var kvp in conditionMappings)
        {
            var destPropName = kvp.Key;
            var memberMapping = kvp.Value;

            // Find the destination property
            var destProp = destProperties.FirstOrDefault(p => p.Name == destPropName);
            if (destProp == null) continue;

            // Generate the value expression
            string? valueExpr = null;
            if (memberMapping.SourceExpression != null)
            {
                // Custom MapFrom expression
                var adjustedExpr = isSourceNullableValueType
                    ? memberMapping.SourceExpression.Replace("source.", $"{sourceVarName}.")
                    : memberMapping.SourceExpression;
                valueExpr = adjustedExpr;
            }
            else if (sourceProperties.TryGetValue(destPropName, out var sourceProp))
            {
                // Convention-based mapping
                valueExpr = $"{sourceVarName}.{sourceProp.Name}";
            }

            if (valueExpr != null)
            {
                // v10.0.0: Apply AddTransform if configured for this type
                if (transformsByType.Count > 0 && sourceProperties.TryGetValue(destPropName, out var srcPropForTransform2))
                {
                    valueExpr = ApplyTransform(valueExpr, srcPropForTransform2.Type, transformsByType);
                }

                // v8.1.0: Apply NullSubstitute if configured (before condition check)
                if (nullSubstituteMappings.TryGetValue(destPropName, out var nullSubstExpr))
                {
                    valueExpr = $"({valueExpr}) ?? {nullSubstExpr}";
                }

                // Adjust Condition expression for nullable value types
                var condExpr = isSourceNullableValueType
                    ? memberMapping.ConditionExpression!.Replace("source.", $"{sourceVarName}.")
                    : memberMapping.ConditionExpression!;

                sb.AppendLine();
                sb.AppendLine($"        var _value = {valueExpr};");
                sb.AppendLine($"        if ({condExpr})");
                sb.AppendLine($"            result.{destPropName} = _value;");
            }
        }

        // v10.0.0: Generate MapFrom with destination parameter assignments
        foreach (var kvp in destParamMappings)
        {
            var destPropName = kvp.Key;
            var memberMapping = kvp.Value;

            var valueExpr = isSourceNullableValueType
                ? memberMapping.SourceExpression!.Replace("source.", $"{sourceVarName}.")
                : memberMapping.SourceExpression!;

            sb.AppendLine();
            sb.AppendLine($"        result.{destPropName} = {valueExpr};");
        }

        // v9.0.0: Generate ForPath assignments
        if (mapping.PathMappings.Count > 0)
        {
            GeneratePathMappings(sb, mapping, sourceVarName, isSourceNullableValueType);
        }

        // If we have PreConditions or Conditions, we used a "result" variable
        if (needsResultVariable)
        {
            sb.AppendLine();
            sb.AppendLine("        return result;");
        }

        sb.AppendLine("    }");
    }

    /// <summary>
    /// v9.0.0: Generates ForPath assignments with intermediate object creation.
    /// </summary>
    private void GeneratePathMappings(
        StringBuilder sb,
        MappingDefinition mapping,
        string sourceVarName,
        bool isSourceNullableValueType)
    {
        // Group path mappings by their first segment to handle intermediate object creation
        var createdIntermediates = new HashSet<string>();

        foreach (var pathMapping in mapping.PathMappings)
        {
            if (pathMapping.IsIgnored || pathMapping.PathSegments.Count == 0)
                continue;

            sb.AppendLine();

            // Build the full path and create intermediate objects if needed
            var currentPath = "result";
            for (int i = 0; i < pathMapping.PathSegments.Count - 1; i++)
            {
                var segment = pathMapping.PathSegments[i];
                var nextPath = $"{currentPath}.{segment}";
                var intermediateKey = string.Join(".", pathMapping.PathSegments.Take(i + 1));

                if (!createdIntermediates.Contains(intermediateKey))
                {
                    // Get the type of this intermediate property from the destination type symbol
                    var propType = GetNestedPropertyType(mapping.DestinationTypeSymbol, pathMapping.PathSegments.Take(i + 1).ToList());

                    if (propType != null && !propType.IsValueType)
                    {
                        sb.AppendLine($"        if ({nextPath} == null)");
                        sb.AppendLine($"            {nextPath} = new {propType.ToDisplayString()}();");
                    }
                    createdIntermediates.Add(intermediateKey);
                }
                currentPath = nextPath;
            }

            // Assign the final value
            var lastSegment = pathMapping.PathSegments.Last();
            var fullPath = $"result.{string.Join(".", pathMapping.PathSegments)}";

            var sourceExpr = pathMapping.SourceExpression ?? $"{sourceVarName}.{lastSegment}";
            if (sourceExpr.StartsWith("source.") && sourceVarName != "source")
            {
                sourceExpr = sourceExpr.Replace("source.", $"{sourceVarName}.");
            }

            sb.AppendLine($"        {fullPath} = {sourceExpr};");
        }
    }

    /// <summary>
    /// v9.0.0: Gets the type of a nested property from path segments.
    /// </summary>
    private static ITypeSymbol? GetNestedPropertyType(ITypeSymbol? typeSymbol, List<string> pathSegments)
    {
        if (typeSymbol == null) return null;

        var currentType = typeSymbol;
        foreach (var segment in pathSegments)
        {
            var prop = currentType.GetMembers()
                .OfType<IPropertySymbol>()
                .FirstOrDefault(p => p.Name == segment);

            if (prop == null) return null;
            currentType = prop.Type;
        }

        return currentType;
    }

    /// <summary>
    /// v9.0.0: Generates constructor invocation with named parameters from ForCtorParam mappings.
    /// </summary>
    private void GenerateCtorParamConstruction(
        StringBuilder sb,
        MappingDefinition mapping,
        string destType,
        string sourceVarName)
    {
        // Generate: var result = new DestType(
        //     paramName: sourceExpr,
        //     ...
        // );
        sb.AppendLine($"        var result = new {destType}(");

        var ctorParams = mapping.CtorParamMappings;
        for (int i = 0; i < ctorParams.Count; i++)
        {
            var param = ctorParams[i];
            var sourceExpr = param.SourceExpression ?? $"{sourceVarName}.{param.ParameterName}";

            // Adjust source expression for the correct variable name
            if (sourceExpr.StartsWith("source.") && sourceVarName != "source")
            {
                sourceExpr = sourceExpr.Replace("source.", $"{sourceVarName}.");
            }

            var comma = i < ctorParams.Count - 1 ? "," : "";
            sb.AppendLine($"            {param.ParameterName}: {sourceExpr}{comma}");
        }

        sb.AppendLine("        );");
        sb.AppendLine();

        // Now we need to also set any remaining properties via object initializer
        // This is done by the calling code after GenerateCtorParamConstruction
        // The calling code should NOT generate "        {" since we already have the object
    }

    /// <summary>
    /// v7.1.0: Generates a mapping method from a lambda converter expression.
    /// </summary>
    private void GenerateLambdaConverterMethod(StringBuilder sb, MappingDefinition mapping)
    {
        var sourceType = mapping.SourceType;
        var destType = mapping.DestinationType;
        var methodName = GetMapperMethodName(mapping.SourceTypeName, mapping.DestinationTypeName);
        var converterExpr = mapping.ConverterLambdaExpression!;

        var isSourceValueType = mapping.SourceTypeSymbol?.IsValueType == true;
        var isSourceNullableValueType = IsNullableValueType(mapping.SourceTypeSymbol);

        sb.AppendLine($"    /// <summary>");
        sb.AppendLine($"    /// Maps {sourceType} to {destType} using inline converter");
        sb.AppendLine($"    /// </summary>");

        if (isSourceValueType && !isSourceNullableValueType)
        {
            // Non-nullable value type source - no null check needed
            sb.AppendLine($"    public static {destType}? {methodName}({sourceType} source)");
            sb.AppendLine("    {");
            sb.AppendLine($"        return {converterExpr};");
            sb.AppendLine("    }");
        }
        else
        {
            // Reference type or nullable value type - standard null handling
            sb.AppendLine($"    [return: global::System.Diagnostics.CodeAnalysis.NotNullIfNotNull(nameof(source))]");
            sb.AppendLine($"    public static {destType}? {methodName}({sourceType}? source)");
            sb.AppendLine("    {");
            sb.AppendLine("        if (source is null) return null;");

            // For nullable value types, extract .Value
            if (isSourceNullableValueType)
            {
                var adjustedExpr = converterExpr.Replace("source.", "source.Value.");
                sb.AppendLine($"        return {adjustedExpr};");
            }
            else
            {
                sb.AppendLine($"        return {converterExpr};");
            }
            sb.AppendLine("    }");
        }
    }

    private string GenerateCustomMappingAssignment(IPropertySymbol destProp, string sourceExpr)
    {
        // The expression should already have "source." prefixed from the ReplaceParameterWithSource call
        // Optimize the expression before using it
        var optimizedExpr = OptimizeNavigationExpression(sourceExpr);
        return $"{destProp.Name} = {optimizedExpr}";
    }

    /// <summary>
    /// Optimizes navigation expressions to reduce duplicate property access.
    /// Transforms: source.A.B != null ? source.A.B.C : default
    /// Into: source.A.B?.C ?? default
    /// </summary>
    private string OptimizeNavigationExpression(string expression)
    {
        // Pattern: captures "source.X.Y != null ? source.X.Y.Z : <default>"
        // where X.Y is accessed twice (null check + property access)
        // Regex groups:
        // 1: navigation path (e.g., "source.Sub.SubSub")
        // 2: property name after the duplicate navigation (e.g., "IAmACoolProperty")
        // 3: default value (e.g., "string.Empty" or "default" or "null")
        var ternaryPattern = @"(\w+(?:\.\w+)+)\s*!=\s*null\s*\?\s*\1\.(\w+)\s*:\s*(.+)";
        var match = Regex.Match(expression, ternaryPattern);

        if (match.Success)
        {
            var navigationPath = match.Groups[1].Value; // e.g., "source.Sub.SubSub"
            var propertyName = match.Groups[2].Value;    // e.g., "IAmACoolProperty"
            var defaultValue = match.Groups[3].Value.Trim(); // e.g., "string.Empty"

            // Transform to: source.Sub.SubSub?.IAmACoolProperty ?? string.Empty
            return $"{navigationPath}?.{propertyName} ?? {defaultValue}";
        }

        // If pattern doesn't match, return original expression unchanged
        return expression;
    }

    private string? GeneratePropertyAssignment(
        IPropertySymbol destProp,
        IPropertySymbol sourceProp,
        MappingDefinition mapping,
        string sourceVarName = "source")
    {
        var destType = destProp.Type;
        var sourceType = sourceProp.Type;

        // Same type - direct assignment
        if (SymbolEqualityComparer.Default.Equals(destType, sourceType))
        {
            return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}";
        }

        // Both nullable or both non-nullable of same underlying type
        var destUnderlying = GetUnderlyingType(destType);
        var sourceUnderlying = GetUnderlyingType(sourceType);

        // T -> T? (implicit conversion)
        if (destUnderlying != null && SymbolEqualityComparer.Default.Equals(destUnderlying, sourceType))
        {
            return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}";
        }

        // T? -> T (need null check or default)
        if (sourceUnderlying != null && SymbolEqualityComparer.Default.Equals(sourceUnderlying, destType))
        {
            if (destType.IsValueType)
            {
                return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name} ?? default";
            }
            else
            {
                return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}!";
            }
        }

        // Enum to string
        if (sourceType.TypeKind == TypeKind.Enum && destType.SpecialType == SpecialType.System_String)
        {
            return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}.ToString()";
        }

        // String to enum
        if (sourceType.SpecialType == SpecialType.System_String && destType.TypeKind == TypeKind.Enum)
        {
            return $"{destProp.Name} = Enum.Parse<{destType.ToDisplayString()}>({sourceVarName}.{sourceProp.Name})";
        }

        // Numeric conversions
        if (IsNumericType(sourceType) && IsNumericType(destType))
        {
            return $"{destProp.Name} = ({destType.ToDisplayString()}){sourceVarName}.{sourceProp.Name}";
        }

        // v7.1.0: Dictionary mapping (before general collection check)
        if (IsDictionaryType(sourceType) && IsDictionaryType(destType))
        {
            return GenerateDictionaryPropertyAssignment(destProp, sourceProp, sourceVarName);
        }

        // Collection mapping
        if (IsCollectionType(sourceType) && IsCollectionType(destType))
        {
            return GenerateCollectionPropertyAssignment(destProp, sourceProp, sourceVarName);
        }

        // Nested complex type - try to find a generated mapper
        if (IsComplexType(sourceType) && IsComplexType(destType))
        {
            var nestedMethodName = GetMapperMethodName(sourceType.Name, destType.Name);
            return $"{destProp.Name} = {nestedMethodName}({sourceVarName}.{sourceProp.Name})";
        }

        // Assignable (implicit conversion)
        if (compilation_IsAssignable(sourceType, destType))
        {
            return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}";
        }

        // Can't map - return null (property will be skipped)
        return null;
    }

    /// <summary>
    /// v7.1.0: Generates collection property assignment with support for all collection types.
    /// </summary>
    private string? GenerateCollectionPropertyAssignment(IPropertySymbol destProp, IPropertySymbol sourceProp, string sourceVarName = "source")
    {
        // v7.1.0: Handle dictionary types separately
        if (IsDictionaryType(destProp.Type))
        {
            return GenerateDictionaryPropertyAssignment(destProp, sourceProp, sourceVarName);
        }

        var destElementType = GetCollectionElementType(destProp.Type);
        var sourceElementType = GetCollectionElementType(sourceProp.Type);

        if (destElementType == null || sourceElementType == null)
        {
            return $"{destProp.Name} = {sourceVarName}.{sourceProp.Name}?.ToList() ?? new()";
        }

        var destKind = GetCollectionKind(destProp.Type);
        var destElemStr = destElementType.ToDisplayString();
        var sourceExpr = $"{sourceVarName}.{sourceProp.Name}";

        // Same element type
        if (SymbolEqualityComparer.Default.Equals(destElementType, sourceElementType))
        {
            return GenerateSameTypeCollectionAssignment(destProp.Name, sourceExpr, destElemStr, destKind);
        }

        // Simple types that can be converted
        if (IsSimpleType(sourceElementType) && IsSimpleType(destElementType))
        {
            var convertExpr = $"{sourceExpr}?.Select(x => ({destElemStr})x)";
            return GenerateConvertedCollectionAssignment(destProp.Name, convertExpr, destElemStr, destKind);
        }

        // Different element types - need mapping
        var elementMethodName = GetMapperMethodName(sourceElementType.Name, destElementType.Name);
        return GenerateMappedCollectionAssignment(destProp.Name, sourceExpr, destElemStr, elementMethodName, destKind);
    }

    /// <summary>
    /// v7.1.0: Generates assignment for same-type collections.
    /// </summary>
    private static string GenerateSameTypeCollectionAssignment(
        string destPropName, string sourceExpr, string elemType, CollectionKind kind)
    {
        return kind switch
        {
            // Array
            CollectionKind.Array =>
                $"{destPropName} = {sourceExpr}?.ToArray() ?? Array.Empty<{elemType}>()",

            // HashSet
            CollectionKind.HashSet =>
                $"{destPropName} = {sourceExpr} != null ? new HashSet<{elemType}>({sourceExpr}) : new HashSet<{elemType}>()",

            // SortedSet
            CollectionKind.SortedSet =>
                $"{destPropName} = {sourceExpr} != null ? new SortedSet<{elemType}>({sourceExpr}) : new SortedSet<{elemType}>()",

            // ObservableCollection
            CollectionKind.ObservableCollection =>
                $"{destPropName} = {sourceExpr} != null ? new ObservableCollection<{elemType}>({sourceExpr}) : new ObservableCollection<{elemType}>()",

            // LinkedList
            CollectionKind.LinkedList =>
                $"{destPropName} = {sourceExpr} != null ? new LinkedList<{elemType}>({sourceExpr}) : new LinkedList<{elemType}>()",

            // Queue (FIFO order preserved)
            CollectionKind.Queue =>
                $"{destPropName} = {sourceExpr} != null ? new Queue<{elemType}>({sourceExpr}) : new Queue<{elemType}>()",

            // Stack (MUST REVERSE to preserve order!)
            CollectionKind.Stack =>
                $"{destPropName} = {sourceExpr} != null ? new Stack<{elemType}>({sourceExpr}.Reverse()) : new Stack<{elemType}>()",

            // List-like (default) - use ToList
            _ => $"{destPropName} = {sourceExpr}?.ToList() ?? new List<{elemType}>()"
        };
    }

