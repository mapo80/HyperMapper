            _ => $"{destPropName} = {selectExpr}?.ToList() ?? new List<{destElemType}>()"
        };
    }

    /// <summary>
    /// v7.1.0: Generates dictionary property assignment.
    /// </summary>
    private string? GenerateDictionaryPropertyAssignment(IPropertySymbol destProp, IPropertySymbol sourceProp, string sourceVarName)
    {
        var (destKeyType, destValueType) = GetDictionaryKeyValueTypes(destProp.Type);
        var (sourceKeyType, sourceValueType) = GetDictionaryKeyValueTypes(sourceProp.Type);

        if (destKeyType == null || destValueType == null || sourceKeyType == null || sourceValueType == null)
            return null;

        var destKeyStr = destKeyType.ToDisplayString();
        var destValueStr = destValueType.ToDisplayString();
        var sourceExpr = $"{sourceVarName}.{sourceProp.Name}";

        // Same key AND value types - direct copy
        if (SymbolEqualityComparer.Default.Equals(destKeyType, sourceKeyType) &&
            SymbolEqualityComparer.Default.Equals(destValueType, sourceValueType))
        {
            return $"{destProp.Name} = {sourceExpr} != null ? new Dictionary<{destKeyStr}, {destValueStr}>({sourceExpr}) : new Dictionary<{destKeyStr}, {destValueStr}>()";
        }

        // Same keys, different values (need value mapping)
        if (SymbolEqualityComparer.Default.Equals(destKeyType, sourceKeyType))
        {
            // Check if value is a simple type conversion
            if (IsSimpleType(sourceValueType) && IsSimpleType(destValueType))
            {
                return $"{destProp.Name} = {sourceExpr} != null ? {sourceExpr}.ToDictionary(kvp => kvp.Key, kvp => ({destValueStr})kvp.Value) : new Dictionary<{destKeyStr}, {destValueStr}>()";
            }

            // Complex value type - need mapper
            var valueMapperName = GetMapperMethodName(sourceValueType.Name, destValueType.Name);
            return $"{destProp.Name} = {sourceExpr} != null ? {sourceExpr}.ToDictionary(kvp => kvp.Key, kvp => {valueMapperName}(kvp.Value)!) : new Dictionary<{destKeyStr}, {destValueStr}>()";
        }

        // Different key types - not supported at compile-time, skip
        return null;
    }

    /// <summary>
    /// v10.0.0: Tries to generate assignment from IncludeMembers.
    /// Looks for matching property in nested member objects.
    /// </summary>
    private string? TryGenerateIncludeMembersAssignment(
        IPropertySymbol destProp,
        Dictionary<string, IPropertySymbol> sourceProperties,
        List<string> includedMembers,
        string sourceVarName = "source")
    {
        var destName = destProp.Name;

        foreach (var memberName in includedMembers)
        {
            if (!sourceProperties.TryGetValue(memberName, out var memberProp))
                continue;

            // Look for a property with the same name in the member object
            var nestedProp = GetPropertyByName(memberProp.Type, destName);
            if (nestedProp != null)
            {
                // Generate null-safe access: source.Member?.Property
                return $"{destProp.Name} = {sourceVarName}.{memberName}?.{destName}";
            }
        }

        return null;
    }

    private string? TryGenerateFlatteningAssignment(
        IPropertySymbol destProp,
        Dictionary<string, IPropertySymbol> sourceProperties,
        ITypeSymbol? sourceTypeSymbol,
        string sourceVarName = "source")
    {
        if (sourceTypeSymbol == null) return null;

        // Try to find nested property (e.g., AddressStreet -> Address.Street)
        var destName = destProp.Name;

        foreach (var kvp in sourceProperties)
        {
            var sourceName = kvp.Key;
            var sourceProp = kvp.Value;

            if (destName.StartsWith(sourceName, StringComparison.Ordinal) &&
                destName.Length > sourceName.Length)
            {
                var remainingName = destName.Substring(sourceName.Length);

                // Check if source property has a nested property with remaining name
                var nestedProp = GetPropertyByName(sourceProp.Type, remainingName);
                if (nestedProp != null)
                {
                    // Generate null-safe access
                    return $"{destProp.Name} = {sourceVarName}.{sourceName}?.{remainingName}";
                }
            }
        }

        return null;
    }

    /// <summary>
    /// v7.1.0: Generates a generic mapping method for open generic types.
    /// </summary>
    private void GenerateOpenGenericMappingMethod(StringBuilder sb, MappingDefinition mapping)
    {
        if (!mapping.IsOpenGeneric || mapping.TypeParameters == null || mapping.OpenSourceType == null || mapping.OpenDestType == null)
            return;

        var methodName = GetMapperMethodName(mapping.SourceTypeName, mapping.DestinationTypeName);
        var typeParamsDecl = string.Join(", ", mapping.TypeParameters);
        var sourceType = mapping.OpenSourceType;
        var destType = mapping.OpenDestType;

        // Get properties from type symbols
        var sourceProps = GetWritableProperties(mapping.SourceTypeSymbol).ToList();
        var destProps = GetWritableProperties(mapping.DestinationTypeSymbol).ToList();

        // Build lookup of source properties by name
        var sourcePropsDict = sourceProps.ToDictionary(p => p.Name, StringComparer.OrdinalIgnoreCase);

        sb.AppendLine($"    /// <summary>");
        sb.AppendLine($"    /// Maps {sourceType} to {destType} (open generic)");
        sb.AppendLine($"    /// </summary>");
        sb.AppendLine($"    [return: global::System.Diagnostics.CodeAnalysis.NotNullIfNotNull(nameof(source))]");
        sb.AppendLine($"    public static {destType}? {methodName}<{typeParamsDecl}>({sourceType}? source)");
        sb.AppendLine("    {");
        sb.AppendLine("        if (source is null) return null;");
        sb.AppendLine($"        return new {destType}");
        sb.AppendLine("        {");

        var assignments = new List<string>();
        foreach (var destProp in destProps)
        {
            if (sourcePropsDict.TryGetValue(destProp.Name, out var sourceProp))
            {
                var assignment = GenerateOpenGenericPropertyAssignment(destProp, sourceProp, mapping.TypeParameters);
                if (assignment != null)
                {
                    assignments.Add(assignment);
                }
            }
        }

        for (int i = 0; i < assignments.Count; i++)
        {
            var suffix = i < assignments.Count - 1 ? "," : "";
            sb.AppendLine($"            {assignments[i]}{suffix}");
        }

        sb.AppendLine("        };");
        sb.AppendLine("    }");
    }

    /// <summary>
    /// v7.1.0: Generates a property assignment for open generic mappings.
    /// </summary>
    private string? GenerateOpenGenericPropertyAssignment(IPropertySymbol destProp, IPropertySymbol sourceProp, List<string> typeParameters)
    {
        // For open generics, we check if types are compatible
        var destType = destProp.Type;
        var sourceType = sourceProp.Type;

        // Same type (including type parameters) - direct assignment
        if (SymbolEqualityComparer.Default.Equals(destType, sourceType))
        {
            return $"{destProp.Name} = source.{sourceProp.Name}";
        }

        // If source is a type parameter (T) and dest is also T, allow assignment
        if (sourceType is ITypeParameterSymbol && destType is ITypeParameterSymbol)
        {
            // Both are type parameters - assume they match (same position)
            return $"{destProp.Name} = source.{sourceProp.Name}";
        }

        // Simple types that are always assignable
        if (IsSimpleType(sourceType) && IsSimpleType(destType))
        {
            if (destType.SpecialType == sourceType.SpecialType)
            {
                return $"{destProp.Name} = source.{sourceProp.Name}";
            }
        }

        // Assignable types
        if (compilation_IsAssignable(sourceType, destType))
        {
            return $"{destProp.Name} = source.{sourceProp.Name}";
        }

        // Can't map automatically - skip
        return null;
    }

