    }

    /// <summary>
    /// v10.0.0: Gets the type name suitable for transform lookup.
    /// </summary>
    private static string GetTypeNameForTransform(ITypeSymbol? type)
    {
        if (type == null) return "";
        return type.ToDisplayString();
    }

    /// <summary>
    /// v10.0.0: Applies type transformation if configured.
    /// </summary>
    private static string ApplyTransform(string valueExpr, ITypeSymbol? type, Dictionary<string, string> transformsByType)
    {
        if (type == null || transformsByType.Count == 0)
            return valueExpr;

        var typeName = GetTypeNameForTransform(type);
        if (transformsByType.TryGetValue(typeName, out var transformExpr))
        {
            // Replace {0} placeholder with the value expression
            return string.Format(transformExpr, valueExpr);
        }

        // Check if it's a nullable type and apply transform to the underlying type
        var underlying = GetUnderlyingType(type);
        if (underlying != null)
        {
            var underlyingTypeName = GetTypeNameForTransform(underlying);
            if (transformsByType.TryGetValue(underlyingTypeName, out var underlyingTransformExpr))
            {
                // For nullable types, need to handle null case
                return string.Format(underlyingTransformExpr, valueExpr);
            }
        }

        return valueExpr;
    }

