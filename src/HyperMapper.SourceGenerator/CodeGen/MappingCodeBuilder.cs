            CollectionKind.LinkedList =>
                $"{destPropName} = {selectExpr} != null ? new LinkedList<{destElemType}>({selectExpr}) : new LinkedList<{destElemType}>()",

            CollectionKind.Queue =>
                $"{destPropName} = {selectExpr} != null ? new Queue<{destElemType}>({selectExpr}) : new Queue<{destElemType}>()",

            // Stack: reverse AFTER mapping to preserve order
            CollectionKind.Stack =>
