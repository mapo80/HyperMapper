    private static string GetMapperMethodName(string sourceTypeName, string destTypeName)
    {
        return $"Map{sourceTypeName}To{destTypeName}";
    }

    private static IEnumerable<IPropertySymbol> GetWritableProperties(ITypeSymbol? typeSymbol)
    {
        if (typeSymbol == null) return Enumerable.Empty<IPropertySymbol>();

        return typeSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => p.SetMethod != null &&
                        p.SetMethod.DeclaredAccessibility == Accessibility.Public &&
                        !p.IsReadOnly &&
                        !p.IsStatic);
    }

    private static Dictionary<string, IPropertySymbol> GetReadablePropertiesDict(ITypeSymbol? typeSymbol)
    {
        if (typeSymbol == null) return new Dictionary<string, IPropertySymbol>();

        return typeSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .Where(p => p.GetMethod != null &&
                        p.GetMethod.DeclaredAccessibility == Accessibility.Public &&
                        !p.IsWriteOnly &&
                        !p.IsStatic)
            .ToDictionary(p => p.Name, p => p, StringComparer.Ordinal);
    }

    private static IPropertySymbol? GetPropertyByName(ITypeSymbol typeSymbol, string name)
    {
        return typeSymbol.GetMembers()
            .OfType<IPropertySymbol>()
            .FirstOrDefault(p => p.Name.Equals(name, StringComparison.Ordinal));
    }

    private static ITypeSymbol? GetUnderlyingType(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol namedType &&
            namedType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T)
        {
            return namedType.TypeArguments[0];
        }
        return null;
    }

    /// <summary>
    /// Checks if the type is Nullable&lt;T&gt; (e.g., int?, Point?).
    /// </summary>
    private static bool IsNullableValueType(ITypeSymbol? type)
    {
        if (type == null) return false;
        return type is INamedTypeSymbol namedType &&
               namedType.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
    }

    private static bool IsNumericType(ITypeSymbol type)
    {
        var underlying = GetUnderlyingType(type) ?? type;
        return underlying.SpecialType switch
        {
            SpecialType.System_Byte => true,
            SpecialType.System_SByte => true,
            SpecialType.System_Int16 => true,
            SpecialType.System_UInt16 => true,
            SpecialType.System_Int32 => true,
            SpecialType.System_UInt32 => true,
            SpecialType.System_Int64 => true,
            SpecialType.System_UInt64 => true,
            SpecialType.System_Single => true,
            SpecialType.System_Double => true,
            SpecialType.System_Decimal => true,
            _ => false
        };
    }

    private static bool IsSimpleType(ITypeSymbol type)
    {
        var underlying = GetUnderlyingType(type) ?? type;
        if (underlying.TypeKind == TypeKind.Enum) return true;

        return underlying.SpecialType switch
        {
            SpecialType.System_Boolean => true,
            SpecialType.System_Byte => true,
            SpecialType.System_SByte => true,
            SpecialType.System_Int16 => true,
            SpecialType.System_UInt16 => true,
            SpecialType.System_Int32 => true,
            SpecialType.System_UInt32 => true,
            SpecialType.System_Int64 => true,
            SpecialType.System_UInt64 => true,
            SpecialType.System_Single => true,
            SpecialType.System_Double => true,
            SpecialType.System_Decimal => true,
            SpecialType.System_Char => true,
            SpecialType.System_String => true,
            SpecialType.System_DateTime => true,
            _ => underlying.ToDisplayString() switch
            {
                "System.Guid" => true,
                "System.DateOnly" => true,
                "System.TimeOnly" => true,
                "System.DateTimeOffset" => true,
                "System.TimeSpan" => true,
                _ => false
            }
        };
    }

    /// <summary>
    /// v7.1.0: Checks if the type is a supported collection type.
    /// Extended to support Dictionary, ObservableCollection, LinkedList, Queue, Stack, SortedSet, ISet, IReadOnlySet.
    /// </summary>
    private static bool IsCollectionType(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol) return true;

        if (type is INamedTypeSymbol namedType)
        {
            var fullName = namedType.OriginalDefinition.ToDisplayString();
            return
                // Existing v7.0.0 collections
                fullName.StartsWith("System.Collections.Generic.List<") ||
                fullName.StartsWith("System.Collections.Generic.IList<") ||
                fullName.StartsWith("System.Collections.Generic.ICollection<") ||
                fullName.StartsWith("System.Collections.Generic.IEnumerable<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlyList<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlyCollection<") ||
                fullName.StartsWith("System.Collections.Generic.HashSet<") ||
                // v7.1.0: Additional collections
                fullName.StartsWith("System.Collections.ObjectModel.ObservableCollection<") ||
                fullName.StartsWith("System.Collections.Generic.LinkedList<") ||
                fullName.StartsWith("System.Collections.Generic.Queue<") ||
                fullName.StartsWith("System.Collections.Generic.Stack<") ||
                fullName.StartsWith("System.Collections.Generic.SortedSet<") ||
                fullName.StartsWith("System.Collections.Generic.ISet<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlySet<");
        }

        return false;
    }

    /// <summary>
    /// v7.1.0: Checks if the type is a dictionary type.
    /// </summary>
    private static bool IsDictionaryType(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol namedType)
        {
            var fullName = namedType.OriginalDefinition.ToDisplayString();
            return fullName.StartsWith("System.Collections.Generic.Dictionary<") ||
                   fullName.StartsWith("System.Collections.Generic.IDictionary<") ||
                   fullName.StartsWith("System.Collections.Generic.IReadOnlyDictionary<");
        }
        return false;
    }

    /// <summary>
    /// v7.1.0: Gets the key and value types from a dictionary type.
    /// </summary>
    private static (ITypeSymbol? KeyType, ITypeSymbol? ValueType) GetDictionaryKeyValueTypes(ITypeSymbol type)
    {
        if (type is INamedTypeSymbol namedType && namedType.TypeArguments.Length == 2)
            return (namedType.TypeArguments[0], namedType.TypeArguments[1]);
        return (null, null);
    }

    /// <summary>
    /// v7.1.0: Determines the collection kind for code generation.
    /// </summary>
    private static CollectionKind GetCollectionKind(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol) return CollectionKind.Array;

        if (type is INamedTypeSymbol namedType)
        {
            var fullName = namedType.OriginalDefinition.ToDisplayString();

            // Dictionary types (2 type parameters)
            if (fullName.StartsWith("System.Collections.Generic.Dictionary<") ||
                fullName.StartsWith("System.Collections.Generic.IDictionary<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlyDictionary<"))
                return CollectionKind.Dictionary;

            // Stack
            if (fullName.StartsWith("System.Collections.Generic.Stack<"))
                return CollectionKind.Stack;

            // Queue
            if (fullName.StartsWith("System.Collections.Generic.Queue<"))
                return CollectionKind.Queue;

            // LinkedList
            if (fullName.StartsWith("System.Collections.Generic.LinkedList<"))
                return CollectionKind.LinkedList;

            // ObservableCollection
            if (fullName.StartsWith("System.Collections.ObjectModel.ObservableCollection<"))
                return CollectionKind.ObservableCollection;

            // SortedSet
            if (fullName.StartsWith("System.Collections.Generic.SortedSet<"))
                return CollectionKind.SortedSet;

            // HashSet, ISet, IReadOnlySet -> HashSet
            if (fullName.StartsWith("System.Collections.Generic.HashSet<") ||
                fullName.StartsWith("System.Collections.Generic.ISet<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlySet<"))
                return CollectionKind.HashSet;

            // List-like collections (including interfaces)
            if (fullName.StartsWith("System.Collections.Generic.List<") ||
                fullName.StartsWith("System.Collections.Generic.IList<") ||
                fullName.StartsWith("System.Collections.Generic.ICollection<") ||
                fullName.StartsWith("System.Collections.Generic.IEnumerable<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlyList<") ||
                fullName.StartsWith("System.Collections.Generic.IReadOnlyCollection<"))
                return CollectionKind.List;
        }

        return CollectionKind.Unknown;
    }

    private static ITypeSymbol? GetCollectionElementType(ITypeSymbol type)
    {
        if (type is IArrayTypeSymbol arrayType)
            return arrayType.ElementType;

        if (type is INamedTypeSymbol namedType && namedType.TypeArguments.Length == 1)
            return namedType.TypeArguments[0];

        return null;
    }

    private static bool IsComplexType(ITypeSymbol type)
    {
        if (type.TypeKind == TypeKind.Enum) return false;
        if (IsSimpleType(type)) return false;
        if (IsCollectionType(type)) return false;
        if (type.SpecialType != SpecialType.None) return false;

        return type.TypeKind == TypeKind.Class || type.TypeKind == TypeKind.Struct;
    }

    private static bool compilation_IsAssignable(ITypeSymbol source, ITypeSymbol dest)
    {
        // Simple check - for full check would need Compilation.ClassifyConversion
        if (SymbolEqualityComparer.Default.Equals(source, dest))
            return true;

        // Check if dest is base class of source
        var current = source.BaseType;
        while (current != null)
        {
            if (SymbolEqualityComparer.Default.Equals(current, dest))
                return true;
            current = current.BaseType;
        }

        // Check interfaces
        foreach (var iface in source.AllInterfaces)
        {
            if (SymbolEqualityComparer.Default.Equals(iface, dest))
                return true;
        }

        return false;
    }

