                var destType = mapping.DestinationType;

                sb.AppendLine($"        // {sourceType} -> {destType}");
                sb.AppendLine($"        if (typeof(TSource) == typeof({sourceType}) &&");
                sb.AppendLine($"            typeof(TDest) == typeof({destType}))");
                sb.AppendLine("        {");

                // v9.0.0: Handle Include<> for polymorphic dispatch
                if (mapping.IncludedDerivedTypes.Count > 0)
                {
                    sb.AppendLine($"            var srcObj = ({sourceType})(object?)source!;");
                    foreach (var (derivedSource, derivedDest) in mapping.IncludedDerivedTypes)
                    {
                        var derivedMethodName = GetMapperMethodName(
                            derivedSource.Contains('.') ? derivedSource.Substring(derivedSource.LastIndexOf('.') + 1) : derivedSource,
                            derivedDest.Contains('.') ? derivedDest.Substring(derivedDest.LastIndexOf('.') + 1) : derivedDest);
                        sb.AppendLine($"            if (srcObj is {derivedSource} derived{derivedSource.Replace(".", "_")})");
                        sb.AppendLine($"                return (TDest?)(object?){mapperClass}.{derivedMethodName}(derived{derivedSource.Replace(".", "_")});");
                    }
                    sb.AppendLine($"            return (TDest?)(object?){mapperClass}.{methodName}(srcObj);");
                }
                else
                {
                    sb.AppendLine($"            return (TDest?)(object?){mapperClass}.{methodName}(({sourceType})(object?)source!);");
                }

                sb.AppendLine("        }");
                sb.AppendLine();
                mappingCount++;
            }
        }

        sb.AppendLine("        // No direct mapping found - return default to trigger fallback");
        sb.AppendLine("        return default;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine($"    /// <summary>Number of direct mappings registered: {mappingCount}</summary>");
        sb.AppendLine($"    public const int MappingCount = {mappingCount};");
        sb.AppendLine("}");

        return sb.ToString();
    }

